"""Regenerate core's capture-watermark masks from the meta repo's brand SVGs.

    python3 dev/brand-masks.py [--meta ../hyprune] [--commit ef0ce64]

Reads the two Bold one-ink lockups at the given meta-repo commit (git show, so
the working tree of the meta repo doesn't matter), verifies their SHA-256
against that commit's brand/SHA256SUMS, rasterises them with resvg and writes:

  assets/brand/*.svg                    verbatim copies of the masters
  assets/brand/*-mask.png               8-bit coverage (alpha) cropped to the ink
  src/render/BrandMasks.hpp             the PNG bytes + crop metadata for C++

Needs resvg (0.48.1 was used) and Pillow. Light work; safe on the laptop.
"""
import argparse, hashlib, io, pathlib, subprocess, tempfile
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
# (name, master scale in px per source unit). The full lockup is used from
# 240 px up to the 1024 px cap, so a 2x master is always downscaled; the small
# one only at 160-239 px, so 1x (840 px) is already >3.5x oversampled.
VARIANTS = [('lockup-bold-horizontal-mono', 2), ('lockup-bold-horizontal-small-mono', 1)]
VIEWBOX = (840, 256)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--meta', default=str(ROOT.parent / 'hyprune'))
    p.add_argument('--commit', default='ef0ce64')
    a = p.parse_args()
    meta = pathlib.Path(a.meta)
    commit = subprocess.check_output(['git', '-C', str(meta), 'rev-parse', a.commit + '^{commit}'], text=True).strip()
    sums = {}
    for line in subprocess.check_output(['git', '-C', str(meta), 'show', f'{commit}:brand/SHA256SUMS'], text=True).splitlines():
        digest, path = line.split(None, 1)
        sums[path.strip()] = digest
    resvg = subprocess.check_output(['resvg', '--version'], text=True).strip()
    out = ROOT / 'assets/brand'
    out.mkdir(parents=True, exist_ok=True)
    header = [
        '// Generated by dev/brand-masks.py; do not edit. See assets/brand/BRAND.md.',
        f'// Source: hyprune/hyprune {commit[:7]} brand/svg/bold/*, resvg {resvg}.',
        '// Artwork: "Hyprune logo by Hyprune contributors", CC-BY-4.0.',
        '#pragma once',
        '#include <cstddef>',
        '#include <cstdint>',
        'namespace hyprune::render::brand {',
        f'inline constexpr float ViewBoxWidth = {VIEWBOX[0]}, ViewBoxHeight = {VIEWBOX[1]};',
        'struct MaskSource {',
        '    const unsigned char *png;',
        '    size_t size;',
        '    float scale;          // master pixels per source unit',
        '    float inkX, inkY;     // crop origin in source units (top-left of painted ink)',
        '};',
    ]
    for name, scale in VARIANTS:
        rel = f'svg/bold/{name}.svg'
        svg = subprocess.check_output(['git', '-C', str(meta), 'show', f'{commit}:brand/{rel}'])
        digest = hashlib.sha256(svg).hexdigest()
        if digest != sums[rel]:
            raise SystemExit(f'{rel}: SHA-256 {digest} does not match SHA256SUMS {sums[rel]}')
        (out / f'{name}.svg').write_bytes(svg)
        with tempfile.TemporaryDirectory() as tmp:
            raster = pathlib.Path(tmp) / 'r.png'
            subprocess.run(['resvg', '-w', str(VIEWBOX[0] * scale), str(out / f'{name}.svg'), str(raster)], check=True)
            alpha = Image.open(raster).convert('RGBA').getchannel('A')
        box = alpha.getbbox()
        mask = alpha.crop(box)
        buf = io.BytesIO()
        mask.save(buf, format='PNG', optimize=True)
        data = buf.getvalue()
        (out / f'{name}-mask.png').write_bytes(data)
        ident = ''.join(w.capitalize() for w in name.replace('lockup-bold-horizontal', 'lockup').split('-'))
        header.append(f'// {rel} sha256 {digest}; mask {mask.size[0]}x{mask.size[1]} at {scale}x, crop {box}')
        header.append(f'inline constexpr unsigned char {ident}Png[] = {{')
        for i in range(0, len(data), 20):
            header.append('    ' + ','.join(str(b) for b in data[i:i + 20]) + ',')
        header.append('};')
        header.append(f'inline constexpr MaskSource {ident}{{{ident}Png, sizeof({ident}Png), {scale}.f, '
                      f'{box[0] / scale:.2f}f, {box[1] / scale:.2f}f}};')
        print(f'{name}: sha256 {digest} ok; mask {mask.size} crop {box} -> {len(data)} bytes')
    header.append('} // namespace hyprune::render::brand')
    (ROOT / 'src/render/BrandMasks.hpp').write_text('\n'.join(header) + '\n')


if __name__ == '__main__':
    main()
