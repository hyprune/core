#!/usr/bin/env python3
"""Embed the vendored SPDX license and exception identifiers (object and library licences, RFC-0011)."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
base=root/'third_party/spdx'
licenses=json.loads((base/'license-ids.json').read_text())+json.loads((base/'license-ids-deprecated.json').read_text())
exceptions=json.loads((base/'exceptions.json').read_text())
def table(name,ids):
    body=',\n'.join('    "'+i+'"' for i in sorted(set(ids)))
    return f'inline constexpr const char *{name}[] = {{\n{body}}};\n'
text='#pragma once\n// Generated by dev/embed-spdx.py from third_party/spdx (see third_party/README.md).\nnamespace hyprune::world::spdx {\n'
text+=table('licenses',licenses)+table('exceptions',exceptions)+'} // namespace hyprune::world::spdx\n'
(root/'src/world/SpdxData.hpp').write_text(text)
